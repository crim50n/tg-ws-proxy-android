#!/usr/bin/env python3
"""Regenerate the vendored Tabler outline subset (Python standard library only)."""

from pathlib import Path
from urllib.request import urlopen
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
VERSION = "v3.31.0"
BASE = f"https://raw.githubusercontent.com/tabler/tabler-icons/{VERSION}"
ICONS = {
    "ArrowLeft": "arrow-left",
    "Trash": "trash",
    "FileUpload": "file-upload",
    "Schema": "schema",
    "PlayerPlay": "player-play",
    "Route": "route",
    "Cloud": "cloud",
    "RouteAltLeft": "route-alt-left",
    "AdjustmentsHorizontal": "adjustments-horizontal",
    "BatteryEco": "battery-eco",
    "Palette": "palette",
    "Receipt": "receipt",
    "Tool": "tool",
    "Settings": "settings",
    "DotsVertical": "dots-vertical",
    "Help": "help",
    "InfoCircle": "info-circle",
    "AlertTriangle": "alert-triangle",
    "AlertCircle": "alert-circle",
    "CircleCheck": "circle-check",
    "WifiOff": "wifi-off",
    "Ban": "ban",
    "Network": "network",
    "Server": "server",
    "ChevronDown": "chevron-down",
    "DeviceMobileDown": "device-mobile-down",
    "PlayerStop": "player-stop",
    "Copy": "copy",
    "Code": "code",
    "Lock": "lock",
    "Bell": "bell",
    "ArrowsLeftRight": "arrows-left-right",
    "ExternalLink": "external-link",
    "Refresh": "refresh",
}
MIRRORED = {"ArrowLeft", "Route", "RouteAltLeft", "ArrowsLeftRight", "ExternalLink"}


def fetch(path):
    with urlopen(f"{BASE}/{path}", timeout=30) as response:
        return response.read().decode("utf-8")


def main():
    lines = [
        "// Generated by tools/generate_tabler_icons.py. Do not edit by hand.",
        f"// Tabler Icons {VERSION}, MIT; see assets/licenses/tabler-icons.txt.",
        "package dev.minios.tgwsproxy.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** Genuine Tabler outline paths, lazily parsed and cached per icon. */",
        "object TablerIcons {",
    ]
    for name, slug in ICONS.items():
        svg = ET.fromstring(fetch(f"icons/outline/{slug}.svg"))
        assert svg.attrib["viewBox"] == "0 0 24 24"
        assert svg.attrib["stroke-width"] == "2"
        lines.extend([
            f"    // https://github.com/tabler/tabler-icons/blob/{VERSION}/icons/outline/{slug}.svg",
            f"    val {name}: ImageVector by lazy {{",
            f'        outline("Tabler.{name}", autoMirror = {str(name in MIRRORED).lower()},',
        ])
        for child in svg:
            assert child.tag == "{http://www.w3.org/2000/svg}path", (slug, child.tag)
            assert set(child.attrib) == {"d"}, (slug, child.attrib)
            lines.append(f'            "{child.attrib["d"]}",')
        lines.extend(["        )", "    }", ""])
    lines.extend([
        "    private fun outline(name: String, autoMirror: Boolean, vararg paths: String): ImageVector {",
        "        val builder = ImageVector.Builder(",
        "            name = name,",
        "            defaultWidth = 24.dp,",
        "            defaultHeight = 24.dp,",
        "            viewportWidth = 24f,",
        "            viewportHeight = 24f,",
        "            autoMirror = autoMirror,",
        "        )",
        "        for (path in paths) {",
        "            builder.addPath(",
        "                pathData = PathParser().parsePathString(path).toNodes(),",
        "                fill = null,",
        "                stroke = SolidColor(Color.Black),",
        "                strokeLineWidth = 2f,",
        "                strokeLineCap = StrokeCap.Round,",
        "                strokeLineJoin = StrokeJoin.Round,",
        "            )",
        "        }",
        "        return builder.build()",
        "    }",
        "}",
    ])
    license_text = fetch("LICENSE")
    output = ROOT / "app/src/main/java/dev/minios/tgwsproxy/ui/icons/TablerIcons.kt"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    license_file = ROOT / "app/src/main/assets/licenses/tabler-icons.txt"
    license_file.parent.mkdir(parents=True, exist_ok=True)
    license_file.write_text(license_text, encoding="utf-8")
    print(f"Generated {len(ICONS)} icons and bundled upstream MIT license.")


if __name__ == "__main__":
    main()
